export function function_auto_declined_phrase() {
  "The words a function writes in its own docstring to ask the canonicalizing pass to leave it alone";
  "Fourteen functions were already saying this in prose before anything read it, all of them in exactly these words, so this is the phrase they chose rather than a new one invented alongside them. Asking them to carry a second marker as well would have been fourteen edits to make a note mean what it already said";
  "Kept in one place so the writing of it and the reading of it cannot drift apart. A phrase spelled out at both ends is a rule that stops working the day somebody rewords one end";
  let phrase = "do NOT auto-canonicalize";
  return phrase;
}
