import { arguments_assert } from "./arguments_assert.mjs";
import { property_get } from "./property_get.mjs";
import { python_code_mirror } from "./python_code_mirror.mjs";
import { file_exists } from "./file_exists.mjs";
import { file_read } from "./file_read.mjs";
import { fn_name } from "./fn_name.mjs";
import { curl_read_hosts } from "./curl_read_hosts.mjs";
import { file_overwrite_deciding } from "./file_overwrite_deciding.mjs";
export async function python_mirror_write(mirror, approved) {
  arguments_assert(arguments, 2);
  ("Writes one mirrored list to the file the guard imports it from, unless that would trust a website nobody approved.");
  ("A generated file is only ever replaced by another. The path comes from a list any edit can change, so without this a mirror pointed at the guard itself would overwrite it.");
  ("The site list decides what may be fetched without asking, and its source is a function any edit can change. So a host the file does not hold yet needs naming in approved, which only curl_read_hosts_approve passes, and that command is not granted: the person sees the hosts in the prompt. Removing a host needs nothing, because that only asks more.");
  ("The comparison is here and not in a helper because this function reaches the deciding writer, so an edit to it cannot land unasked, while a helper could be edited to answer that nothing was new.");
  ("A refusal is returned and not thrown, so the other lists still get written. It cannot pass unnoticed: the list stays stale and the drift gate stays red until it is approved.");
  let path = property_get(mirror, "path");
  let code = python_code_mirror(mirror);
  let present = await file_exists(path);
  let before = "";
  if (present) {
    before = await file_read(path);
  }
  let header = "# GENERATED by " + fn_name("python_code_mirror");
  if (present && !before.startsWith(header)) {
    throw new Error(
      "not written, because this file was not generated: " + path,
    );
  }
  let hosts_path = ".claude/hooks/" + curl_read_hosts.name + ".py";
  if (path === hosts_path) {
    let held = [];
    if (present) {
      let opener = " = {";
      let start = before.indexOf(opener) + opener.length;
      let end = before.lastIndexOf("}");
      held = JSON.parse("[" + before.slice(start, end) + "]");
    }
    let source = property_get(mirror, "source");
    let names = source();
    let additions = names.filter(
      (name) => !held.includes(name) && !approved.includes(name),
    );
    if (additions.length > 0) {
      let refused = {
        refused: path,
        additions,
        approve:
          "node scripts/ai.mjs " +
          fn_name("curl_read_hosts_approve") +
          " " +
          additions.join(","),
      };
      return refused;
    }
  }
  await file_overwrite_deciding(path, code);
  let written = {
    written: path,
  };
  return written;
}
