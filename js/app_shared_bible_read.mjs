export async function app_shared_bible_read(context, verse_action) {
  let root = app_shared_mobile_default_font_size(context);
  ("clear first so this reader can re-render in place (mode switch) instead of only on a fresh page load");
  html_clear(root);
  html_margin_0(root);
  let bc = app_shared_bar_content_root(root);
  let shell = property_get(bc, "shell");
  let content = property_get(bc, "content");
  app_shared_content_column_pad(content);
  html_flex_column_gap(content, "0");
  let bar = property_get(bc, "bar");
  let t = html_button_copy_text();
  let max = app_shared_bible_chosen_max();
  let v2 = number_to_words(max);
  let padded = text_pad_space_quote_double(t);
  let help_text = text_combine_multiple([
    "Tap up to ",
    v2,
    " verse numbers, then ",
    padded,
    " to save that passage",
  ]);
  let hash = html_hash_object_get();
  ("A language code in the link that names no bible we have is answered here rather than read past. Read past, it was dropped without a word and the chapter opened in whatever languages happened to be left - so somebody sent a link with one letter wrong read the wrong bible and nothing anywhere said so. It is the same screen the sent-a-verse page shows, from the same function, so a wrong link reads the same whichever bible surface it lands on.");
  let unknown_shown = app_shared_bible_hash_languages_unknown_shown_is(
    content,
    hash,
  );
  if (unknown_shown) {
    return;
  }
  let c = app_shared_bible_chapter_hash_get_or_empty(hash);
  let b = app_shared_bible_book_hash_get(hash);
  let key = app_shared_bible_reference_hash_key();
  let ref = property_get_or(hash, key, "");
  let ref_line = text_replace(ref, "+", " ");
  let ref_mode = text_empty_is(c) && text_empty_not_is(ref);
  let languages_chosen = app_shared_bible_hash_to_languages_chosen(hash);
  let language = list_last(languages_chosen);
  let primary_folder = ebible_language_to_bible_folder(language);
  let books = await ebible_version_books_browser(primary_folder);
  html_centered(bar);
  if (text_empty_is(c) && text_empty_is(ref) && text_empty_not_is(b)) {
    await app_shared_bible_choose_chapter(
      bar,
      content,
      b,
      books,
      primary_folder,
    );
    app_shared_bible_settings_gear(bar, content, languages_chosen, context);
    return;
  }
  let bible_folder = ebible_folder_english();
  let books_en = await ebible_version_books_browser(bible_folder);
  if (ref_mode) {
    let ref_chapters = app_shared_bible_ref_chapter_codes(ref_line, books_en);
    if (list_multiple_is(ref_chapters)) {
      app_shared_bible_ref_chapters_guard(content, ref_chapters, books_en);
      app_shared_bible_settings_gear(bar, content, languages_chosen, context);
      return;
    }
  }
  let dismiss_help = app_shared_dismissable_message(
    app_shared_bible_read,
    "chapter_help_dismissed",
    bar,
    help_text,
  );
  ("the count sits UNDER the chapter rather than over it. It is empty until a verse is picked, so it arrives while the reader is looking at the text - and arriving in the top bar it would take its height off the top of the reading, sliding the verse just tapped down the screen away from the thumb that tapped it. Under the body the same height comes off the bottom and nothing already on the screen moves.");
  let foot = html_bar_foot(shell);
  html_centered(foot);
  let count_status = html_p(foot);
  app_shared_text_deemphasized(count_status);
  ("a paragraph carries a blank line's worth of margin whether or not it says anything - so with no margin an empty count costs no height at all, and the chapter fills the screen until there is something to say");
  html_margin_0(count_status);
  let chapter_code = text_empty_is(c)
    ? app_shared_bible_chapter_code_default()
    : c;
  if (ref_mode) {
    let ref_chapter = await app_shared_bible_ref_chapter_code(ref_line);
    if (null_is(ref_chapter)) {
      ref_mode = false;
    } else {
      chapter_code = ref_chapter;
    }
  }
  let key4 = app_shared_bible_verse_hash_key();
  let v_hash = property_get_or(hash, key4, "");
  async function chapter_previous() {
    await app_shared_bible_change(
      chapter_code,
      languages_chosen,
      list_previous_wrap,
    );
  }
  async function chapter_next() {
    await app_shared_bible_change(
      chapter_code,
      languages_chosen,
      list_next_wrap,
    );
  }
  let verse_numbers_chosen = text_empty_is(v_hash)
    ? []
    : text_split(v_hash, "-");
  let languages_verses = [];
  let updates = [];
  let verse_rows = [];
  if (ref_mode) {
    app_shared_bible_book_chapter(bar, content, chapter_code, books);
    function view_whole_chapter() {
      let property_name = verse_number_key();
      let verse_numbers = list_map_property(primary_verses, property_name);
      let first = list_first(verse_numbers);
      let last = list_last(verse_numbers);
      let endpoints = equal(first, last) ? [first] : [first, last];
      app_shared_bible_code_verses_open(chapter_code, endpoints);
    }
    app_shared_button(bar, "View whole chapter", view_whole_chapter);
  } else {
    app_shared_button_arrow_left(bar, chapter_previous);
    app_shared_bible_book_chapter(bar, content, chapter_code, books);
    app_shared_button_arrow_right(bar, chapter_next);
  }
  app_shared_bible_settings_gear(bar, content, languages_chosen, context);
  async function fetch_language(lc) {
    let r = await app_shared_bible_fetch_language(
      lc,
      ref_mode,
      ref_line,
      chapter_code,
    );
    return r;
  }
  await list_map_unordered_add_async(
    languages_chosen,
    fetch_language,
    languages_verses,
  );
  languages_verses = list_filter_null_not_is(languages_verses);
  let show_language_names = list_multiple_is(languages_verses);
  let primary_verses = list_last_property(languages_verses, "verses");
  async function render_verse(v) {
    let property_name3 = verse_number_key();
    let verse_number_v = property_get(v, property_name3);
    let verse_chapter_code = property_get_or(v, "chapter_code", chapter_code);
    let verse_book_code = ebible_chapter_code_to_book(verse_chapter_code);
    let verse_book_name = ebible_book_code_to_name(books_en, verse_book_code);
    let verse_chapter_name = ebible_chapter_code_to_name(verse_chapter_code);
    let p = html_p(content);
    html_display_grid(p);
    let left = app_shared_bible_verse_number_gutter();
    let columns = text_combine(left, " 1fr");
    html_style_set(p, "grid-template-columns", columns);
    let style_value = app_shared_spaced_small_gap();
    html_style_set(p, "column-gap", style_value);
    ("when the primary (spine) language reads right-to-left, mirror the whole verse row: direction rtl moves the number gutter to the right and flows the row right-to-left, matching the verse text's own detected direction, so an RTL reader gets RTL numbers too");
    let primary_text = property_get_or(v, "text", "");
    let row_rtl = text_rtl_is(primary_text);
    if (row_rtl) {
      html_style_set(p, "direction", "rtl");
    }
    let r = app_shared_bible_toggle_update(
      updates,
      verse_numbers_chosen,
      verse_number_v,
      verse_chapter_code,
      languages_verses,
      p,
    );
    let select = property_get(r, "select");
    function select_persist() {
      select();
      app_shared_bible_read_persist_selection(verse_numbers_chosen);
      dismiss_help();
      app_shared_bible_read_count_refresh(
        verse_numbers_chosen,
        max,
        count_status,
      );
    }
    let number = app_shared_button(p, verse_number_v, select_persist);
    ("each verse row is its own grid, so the number gutter is a fixed track and the button inside it used to size itself to its digits - a one-digit button came out narrower than a two-digit one. Stretching the button across the whole track is what makes every verse number button the same width, zero side padding keeps a three-digit number (Psalm 119) inside that width, and centering puts the digits in the middle of the button");
    html_style_justify_self(number, "stretch");
    html_style_padding_x(number, "0");
    html_centered(number);
    let text_cell = html_div(p);
    let entries = app_shared_bible_verse_entries(
      languages_verses,
      verse_number_v,
      show_language_names,
    );
    app_shared_bible_verse_texts(text_cell, entries);
    html_margin_0(p);
    ("a verse row's own inset, and the two directions are deliberately not the same number. Down the page the padding is a separation - it is what holds one verse apart from the next - so it keeps a gap the eye can read. Left and right it is an edge, sitting on top of the reading column's own edge gap and pushing the verse number away from the side of the screen twice over, which is the narrowest thing on a phone made narrower for nothing. The row above the first verse is the same padding worn against the chapter bar, so a smaller number closes that band too.");
    let value = app_shared_spaced_neighbor_gap();
    html_style_padding_y(p, value);
    let value2 = app_shared_spaced_frame_gap();
    html_style_padding_x(p, value2);
    let update = property_get(r, "update");
    let copy = property_get(r, "copy");
    let actions = html_div(content);
    html_centered(actions);
    html_display_none(actions);
    let verse_buttons = html_div(actions);
    app_shared_bible_biblehub_buttons(
      verse_buttons,
      verse_chapter_name,
      verse_book_name,
      verse_number_v,
    );
    ("the switch to the other reader stands right after the reference buttons and before copy, in the order the single-verse view puts the same row in, so moving between the two readers does not move the buttons under your thumb");
    verse_action(context, actions, verse_chapter_code, verse_number_v);
    app_shared_button(actions, t, copy);
    async function share() {
      await app_shared_bible_share(
        verse_book_name,
        verse_chapter_name,
        verse_numbers_chosen,
        languages_chosen,
      );
    }
    let text = html_button_share_text();
    app_shared_button(actions, text, share);
    function row_update() {
      update();
      let right = app_shared_bible_read_selection_last(verse_numbers_chosen);
      let is_last = equal(verse_number_v, right);
      let hidden = not(is_last);
      html_display_none_or_block(hidden, actions);
      let b2 = list_multiple_is(verse_numbers_chosen);
      let single = is_last && not(b2);
      let hidden2 = not(single);
      html_display_none_or_block(hidden2, verse_buttons);
    }
    list_add(verse_rows, {
      verse_number: verse_number_v,
      p,
    });
    return row_update;
  }
  await list_map_add_async(primary_verses, render_verse, updates);
  html_page_bottom_space(content);
  app_shared_bible_read_count_refresh(verse_numbers_chosen, max, count_status);
  async function resume() {
    if (list_empty_is(verse_numbers_chosen)) {
      return;
    }
    invoke_multiple(updates);
    let property_name4 = verse_number_key();
    let ordered = list_map_property(verse_rows, property_name4);
    let item = list_first(verse_numbers_chosen);
    let index = list_index_of(ordered, item);
    if (greater_than_equal(index, 0)) {
      let component = list_get_property(verse_rows, index, "p");
      await html_scroll_center_now(component);
    }
  }
  promise_later(resume);
}
