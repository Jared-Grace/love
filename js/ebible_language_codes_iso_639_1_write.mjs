import { arguments_assert } from "./arguments_assert.mjs";
import { iso_639_1_offered_matches } from "./iso_639_1_offered_matches.mjs";
import { property_get } from "./property_get.mjs";
import { not_equal } from "./not_equal.mjs";
import { property_set } from "./property_set.mjs";
import { ebible_language_codes_iso_639_1_baseline_path } from "./ebible_language_codes_iso_639_1_baseline_path.mjs";
import { file_exists } from "./file_exists.mjs";
import { file_read_json } from "./file_read_json.mjs";
import { object_property_names } from "./object_property_names.mjs";
import { text_combine_multiple } from "./text_combine_multiple.mjs";
import { fn_name } from "./fn_name.mjs";
import { function_new_getter_rewrite } from "./function_new_getter_rewrite.mjs";
import { object_baseline_grow_write } from "./object_baseline_grow_write.mjs";
export async function ebible_language_codes_iso_639_1_write() {
  "Writes the table of two-letter ISO 639-1 codes that each name exactly one language offered here, beside the code it is offered under - so a link a person types with the two letters they know, like es, opens that language in the browser, where the ISO tables this is read from are not available.";
  "A two-letter code that more than one offered language answers to is left out rather than guessed at, and so is one that none answers to - such a link still reaches whatever already tells a reader a code is unknown.";
  arguments_assert(arguments, 0);
  let matches = await iso_639_1_offered_matches();
  let table = {};
  for (let m of matches) {
    let found = property_get(m, "matches");
    if (not_equal(found.length, 1)) {
      continue;
    }
    let [only] = found;
    let property_name = property_get(m, "iso_639_1");
    let value = property_get(only, "stored");
    property_set(table, property_name, value);
  }
  ("Every entry already recorded is kept as it was, even one a language added since now makes ambiguous: a link somebody kept meant that language when it was made, and a regenerated table must not quietly open another one or none.");
  let path = ebible_language_codes_iso_639_1_baseline_path();
  let recorded = {};
  if (await file_exists(path)) {
    recorded = await file_read_json(path);
  }
  for (let code of object_property_names(recorded)) {
    let value2 = property_get(recorded, code);
    property_set(table, code, value2);
  }
  let meaning = text_combine_multiple([
    "Each two-letter ISO 639-1 code that exactly one offered language answers to, beside the code that language is offered under. Generated by ",
    fn_name("ebible_language_codes_iso_639_1_write"),
    " - an edit made here is thrown away the next time it is generated.",
  ]);
  await function_new_getter_rewrite(
    fn_name("ebible_language_codes_iso_639_1"),
    meaning,
    table,
  );
  await object_baseline_grow_write(path, table);
  let count = object_property_names(table).length;
  let r = {
    count,
  };
  return r;
}
