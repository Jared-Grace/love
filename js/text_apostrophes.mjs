export function text_apostrophes() {
  "Every mark people type where an apostrophe goes, the straight one first.";
  "Phones and keyboards each type a different one, so a question about the apostrophe has to ask about all of them, and asking here keeps them from being spelled again in each place that asks.";
  let marks = ["'", "`", "’", "‘", "´", "ʼ", "′", "＇"];
  return marks;
}
