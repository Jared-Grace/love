export function app_learn_js_expression_written_shapes_called() {
  arguments_assert(arguments, 0);
  ('lines built with the called operators other than Math.floor and with the actions reached by a dot, alone and inside other operators, so the sweep sees how each prints: Math.ceil(7 / 2) * 2, 1 + Math.abs(2 - 5), a.includes("joy"), a.indexOf("joy") + 1, a.concat(b), a.slice(1 + 1), a.join(", ")');
  ("Arrived 2026-11-22, at the human's asking: Math.ceil, Math.abs, .includes, .indexOf, .concat, .slice and .join were each given a strength for the lessons that step through them, but no shape here ever held one, so the gate named all seven as never printed.");
  let minus = js_operator_minus_symbol();
  let plus = js_operator_plus_symbol();
  let times = js_operator_asterisk_symbol();
  let shapes = [];
  let halved = app_learn_js_expression_node(7, "/", 2);
  let ceiled = app_learn_js_expression_node_before("Math.ceil", halved);
  list_add(shapes, ceiled);
  let ceiled_times = app_learn_js_expression_node(ceiled, times, 2);
  list_add(shapes, ceiled_times);
  let difference = app_learn_js_expression_node(2, minus, 5);
  let distance = app_learn_js_expression_node_before("Math.abs", difference);
  list_add(shapes, distance);
  let distance_plus = app_learn_js_expression_node(1, plus, distance);
  list_add(shapes, distance_plus);
  let words = app_learn_js_expression_name("a", ["love", "joy", "peace"]);
  let more = app_learn_js_expression_name("b", ["patience", "kindness"]);
  let symbol = app_learn_js_operator_includes_symbol();
  let including = app_learn_js_expression_node(words, symbol, "joy");
  list_add(shapes, including);
  let symbol2 = app_learn_js_operator_index_of_symbol();
  let indexing = app_learn_js_expression_node(words, symbol2, "joy");
  list_add(shapes, indexing);
  let indexing_plus = app_learn_js_expression_node(indexing, plus, 1);
  list_add(shapes, indexing_plus);
  let symbol3 = app_learn_js_operator_concat_symbol();
  let joined_arrays = app_learn_js_expression_node(words, symbol3, more);
  list_add(shapes, joined_arrays);
  let start = app_learn_js_expression_node(1, plus, 1);
  let symbol4 = app_learn_js_operator_slice_symbol();
  let sliced = app_learn_js_expression_node(words, symbol4, start);
  list_add(shapes, sliced);
  let symbol5 = app_learn_js_operator_join_symbol();
  let joined = app_learn_js_expression_node(words, symbol5, ", ");
  list_add(shapes, joined);
  return shapes;
}
