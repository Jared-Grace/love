export function baseline_growth_guarded_is(imports) {
  "whether a ratchet writer importing these names refuses to record what its file did not already hold";
  "the words growth assert are looked for anywhere inside a name rather than at the end of it. the one every ratchet shares its comparison through ends in generic instead, and a first draft of this asked for the ending and called a writer an offender while it was doing exactly the right thing";
  "kept apart from the sweep, and handed a plain list of names rather than a function to go and read. the sweep comes back empty on a healthy repo, so a broken judgment and a working one look identical there, and this is the only place the difference can be seen. a list is also something a corpus can invent, which a real function's imports are not";
  "A WRITER THAT SHRINKS BY CONSTRUCTION COUNTS TOO, AND FOR A BETTER REASON THAN THE ASSERTS. It writes a subset of what the record already held, so growth is unrepresentable there rather than refused - which is what the asserts were reaching for. This is a widening of what counts as a refusal, so it has to be earned rather than granted: the one name accepted here is asked for exactly, not matched by shape, and it carries the proof in its own prose and calls an assert on its subset besides.";
  "The asserts are matched by words inside a name because there are several of them and more will be written. This is a single function, so it is named.";
  arguments_assert(arguments, 1);
  let guards = list_filter_text_includes(imports, "growth_assert");
  let asserted = list_empty_not_is(guards);
  if (asserted) {
    return asserted;
  }
  let f_name = fn_name("baseline_known_shrink_write");
  let shrinks = list_includes(imports, f_name);
  return shrinks;
}
