import { arguments_assert } from "./arguments_assert.mjs";
export function red_proof_claim_phrases() {
  arguments_assert(arguments, 0);
  ("The runs of words a case writes when it claims to be the only one holding some wrong version down.");
  ("A case says why it is there, and the strongest thing it can say is that nothing else here catches what it catches. That sentence is exactly the sort of claim that rots: another case is added later, or a wrong version is sharpened, and the sentence goes on saying it while the machine's own record says otherwise. Three of them were wrong at once in one corpus, and each had been read past twice by somebody looking for that very thing.");
  ("They are deliberately few and narrow, because the cost of a wrong catch here falls on somebody rewording a true sentence. A case saying it is the only one where the lag is not a number is talking about the numbers in front of it rather than about what it refuses, and would be asked to say so differently - which is a fair thing to ask, but only worth asking where the words really do read as a claim about the other cases.");
  let phrases = [
    "nowhere else",
    "the only case",
    "only this case",
    "no other case",
  ];
  return phrases;
}
