import { text_combine_multiple } from "./text_combine_multiple.mjs";
import { fn_name } from "./fn_name.mjs";
import { arguments_assert } from "./arguments_assert.mjs";
import { bible_glyph_chapter_built } from "./bible_glyph_chapter_built.mjs";
import { list_add } from "./list_add.mjs";
import { function_constant_json_write } from "./function_constant_json_write.mjs";
export async function bible_glyph_chapter_built_samples_write() {
  arguments_assert(arguments, 0);
  ("Writes a handful of built picture Bible chapters into a function a page can import, so a phone can show built chapters beside hand-written ones before any built chapter is stored anywhere.");
  ("IT IS A SAMPLE AND NOT THE STORE. A built chapter needs the interlinear, which is far too big for a phone, so a page can only show one that was built here first. The whole Bible built this way belongs in storage, one file a chapter; four chapters written into the bundle are enough to look at and small enough not to matter.");
  ("THE FOUR ARE CHOSEN TO DISAGREE. Genesis one and Psalm twenty three are Hebrew, the gospel and the letter are Greek, and the letter is where the hand-written chapter lags the table furthest, so a reader looking at these sees both what a built chapter keeps and what it adds.");
  let codes = ["GEN01", "PSA023", "JHN14", "1JN04"];
  let samples = [];
  for (let chapter_code of codes) {
    let built = await bible_glyph_chapter_built(chapter_code);
    list_add(samples, built);
  }
  let path = await function_constant_json_write(
    "bible_glyph_chapter_built_samples",
    [
      "A handful of picture Bible chapters BUILT from the interlinear, each word its Strong's number and its English, for a page to show beside the hand-written chapters.",
      text_combine_multiple([
        "Generated by ",
        fn_name("bible_glyph_chapter_built_samples_write"),
        " - never edit it by hand, run that again.",
      ]),
    ],
    samples,
  );
  return path;
}
