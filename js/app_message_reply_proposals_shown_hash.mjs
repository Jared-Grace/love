import { arguments_assert } from "./arguments_assert.mjs";
import { functions_closure_source_hash } from "./functions_closure_source_hash.mjs";
import { fn_name } from "./fn_name.mjs";
export async function app_message_reply_proposals_shown_hash() {
  arguments_assert(arguments, 0);
  ("One short word for all the code the reply rules screen's answer is worked out by, so an answer saved under it is good for as long as the word stays the same.");
  ("★ THE WORD COVERS THE SCREEN'S OWN CODE TOO, NOT ONLY THE RULES, because the list of changes is reached from it; an edited change then changes the word. Data that is not code, the real messages and the case files, is outside this word, which is why whoever keeps a saved answer also redoes it by age.");
  let hash = await functions_closure_source_hash([
    fn_name("reply_attempt"),
    fn_name("app_shared_message_reply_choices"),
    fn_name("app_message_reply_proposals_shown"),
  ]);
  return hash;
}
