import { js_operator_plus_symbol } from "./js_operator_plus_symbol.mjs";
import { js_operator_asterisk_symbol } from "./js_operator_asterisk_symbol.mjs";
import { range_from } from "./range_from.mjs";
import { list_shuffle_take } from "./list_shuffle_take.mjs";
import { list_sort_number } from "./list_sort_number.mjs";
import { list_take } from "./list_take.mjs";
import { list_skip } from "./list_skip.mjs";
import { each } from "./each.mjs";
import { list_shuffle } from "./list_shuffle.mjs";
import { list_get } from "./list_get.mjs";
import { app_code_expression_node } from "./app_code_expression_node.mjs";
export function app_code_lesson_expression_either_first_expression_plus_times() {
  arguments_assert(arguments, 0);
  ("four numbers and three operators, a plus of two numbers on the left and a times on the right, both ready at once and neither of them ready for the same reason: 2 + 3 + 4 * 5");
  ("★ THE OTHER SHAPE THAT LEAVES TWO OPERATORS READY, AND THE ONE THAT SHOWS WHY. Its sister line puts a times on each side of a plus, where both sides go first because both are times - which reads as though matching ends were the reason. Here the ends do not match. The times on the right goes first because it is stronger than the plus holding it; the plus on the left goes first because it is the leftmost of two pluses. Two different reasons, and the choice is free anyway - so a learner who saw only the matching line has been shown a coincidence and a learner who sees this one has been shown the rule.");
  ("The times must stand on the RIGHT and cannot be shuffled to the left. Written the other way round the line reads 4 * 5 + 2 + 3, which hangs as ((4 * 5) + 2) + 3 - the plus on its left is then waiting on the times and only one operator is ready. So the shape that looks like a mirror of this one is not another line of this lesson at all, it is a line of the lesson before it.");
  ("What survives the asymmetry is the thing the lesson is for: neither the leftmost operator nor the rightmost one is the answer, because both of them are. A learner cannot be right here by always reaching for one end.");
  let plus = js_operator_plus_symbol();
  let times = js_operator_asterisk_symbol();
  let smallest = 2;
  let largest = 7;
  let choices = range_from(smallest, largest);
  let count = 4;
  ("The two sides cannot come to the same value, and are built so rather than checked so: the two smallest of the four numbers are added and the two largest are multiplied. Four numbers drawn from two to seven sort so that the sum is at most nine and the product at least twenty, so no draw can put two matching values under a sentence saying the order does not matter - which would show a learner the wrong reason for it.");
  let numbers = list_shuffle_take(choices, count);
  let pair_count = 2;
  list_sort_number(numbers);
  let added_pair = list_take(numbers, pair_count);
  let times_pair = list_skip(numbers, pair_count);
  ("which of a pair is written first is drawn again, because the sorting is only how the two sides are kept from agreeing and left showing it would put the smaller number first on both sides every time");
  each([added_pair, times_pair], list_shuffle);
  let one_index = 0;
  let other_index = 1;
  let added_one = list_get(added_pair, one_index);
  let added_other = list_get(added_pair, other_index);
  let added = app_code_expression_node(added_one, plus, added_other);
  let times_one = list_get(times_pair, one_index);
  let times_other = list_get(times_pair, other_index);
  let multiplied = app_code_expression_node(times_one, times, times_other);
  let tree = app_code_expression_node(added, plus, multiplied);
  return tree;
}
