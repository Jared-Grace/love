import { arguments_assert } from "./arguments_assert.mjs";
export function bless_still_chance(walker) {
  arguments_assert(arguments, 1);
  ("How likely this kind of person is to stop and stand about instead of taking their next");
  ("step.");
  ("The two kinds want opposite answers, which is why it is asked of the kind rather than");
  ("of the street. Somebody out walking who kept stopping is not out walking; somebody");
  ("outside their own front door who kept stepping is not outside their own front door.");
  ("One number for both would have made the walkers dawdle to say that the neighbours were");
  ("standing about, or made the neighbours pace to say that the walkers were getting");
  ("somewhere.");
  ("A walker stops about one tick in fourteen, which is enough that no two walkers stay in");
  ("step and few enough that they plainly have somewhere to be.");
  ("Somebody at home stops about one tick in eight, so they are nearly always moving even");
  ("though standing there is their whole business. That is not a contradiction: a person on");
  ("their own doorstep still shifts about constantly, and it is the size of what they do");
  ("rather than the frequency of it that says they are at home - they move a pace and come");
  ("back, while a walker's paces add up and take them out of sight.");
  ("It used to be the other way round, stopping more often than not, and the street was");
  ("wrong for it. Most people here live at a door, so their answer is very nearly the");
  ("street's answer, and at better than even odds each of them was standing through most of");
  ("a stretch of turns - which read as a crowd waiting for something rather than a crowd");
  ("going about its day. A pavement is only still when everybody on it has stopped to");
  ("listen to somebody, and nobody here is speaking.");
  ("It has since come down three times, and the floor it is heading for is not nought.");
  ("Somebody who never once pauses is a wind-up toy, and the pauses are also what keeps the");
  ("doorstep crowd from moving as one body - drop them and the whole street steps on the");
  ("same beat.");
  ("The third fall was asked for as more motion overall, and it landed here rather than on");
  ("how LONG a stop lasts, which is worth writing down because the length is where most of");
  ("the stillness actually is. A stop runs two to five turns held one to three paces each,");
  ("so it costs about seven paces of standing however rarely it is entered; at one tick in");
  ("ten a walker took about nine steps and then stood for seven, which is a person moving");
  ("barely over half the time, and the doorstep crowd rather less. Shortening the stop");
  ("instead would have bought the same motion by making every stop a worse stop - a stretch");
  ("of turns is only readable as somebody who has stopped to look at something if it lasts");
  ("long enough to be read, and there is a length below which it goes back to being the");
  ("stutter it used to be. Entering fewer of them costs nothing: the ones that happen are");
  ("exactly as good, there are simply more paces between them.");
  ("Fourteen and eight are the same third off each, which keeps the two kinds the distance");
  ("apart they were. The walker now moves about two thirds of the time and the neighbour");
  ("about half, against a bit over half and two fifths before.");
  if (walker) {
    let going = 0.07;
    return going;
  }
  let home = 0.12;
  return home;
}
