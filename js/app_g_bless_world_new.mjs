import { arguments_assert } from "./arguments_assert.mjs";
import { list_first } from "./list_first.mjs";
import { app_g_map_generate } from "./app_g_map_generate.mjs";
import { g_coordinates } from "./g_coordinates.mjs";
import { g_coordinates_land_reachable_get } from "./g_coordinates_land_reachable_get.mjs";
import { g_player_img_get } from "./g_player_img_get.mjs";
import { g_player_initialize } from "./g_player_initialize.mjs";
import { app_g_bless_blocks } from "./app_g_bless_blocks.mjs";
import { app_g_bless_blocks_raise } from "./app_g_bless_blocks_raise.mjs";
import { app_g_bless_people } from "./app_g_bless_people.mjs";
import { app_g_bless_player_place } from "./app_g_bless_player_place.mjs";
import { app_g_bless_world } from "./app_g_bless_world.mjs";
export function app_g_bless_world_new() {
  arguments_assert(arguments, 0);
  ("A fresh world to walk about in - ground, a column of blocks built into it, a player");
  ("standing on the first of them, and a crowd living along all of them.");
  ("Nearly every step of it is the gospel game's own generator. The ground it makes, the way");
  ("it works out which land is actually reachable, and the way it sets somebody down on it");
  ("are not opinions about that game; they are what a walkable world is. Writing a second");
  ("set would have given this game a world that walked slightly differently, and every later");
  ("fix to walking would then have to be made twice.");
  ("Only the blocks and the crowd are this game's own, because only those differ: those");
  ("people are here to be seen and prayed for rather than talked to, and a prayer climbs");
  ("through the places they live in, so those places have to exist on the ground.");
  ("The order is the whole of it. The blocks are decided first because everything after is");
  ("measured from where they landed; they are built into the ground next; the reachable land");
  ("is asked for only THEN, because building changed what the ground is - walls where there");
  ("was grass, path where there was water - and a list made earlier would still be calling");
  ("those squares what they used to be, so the player would be refused a walk down a street");
  ("they can see and offered one through a wall they cannot.");
  ("The player is made the gospel game's way and then MOVED onto the pavement, rather than");
  ("the pavement being built around wherever they landed. Being made first is what takes");
  ("their own picture out of the crowd's; being moved after is what puts the game's first");
  ("act - look at a person, pray for them - in front of them the moment it opens.");
  ("Onto the FIRST block, because the crowd is numbered from the beginning of the line and");
  ("the first sixty of them live there. Set down at the far end the player would open the");
  ("game beside the block the ladder means them to reach second.");
  ("Every block is handed to the world as the places named so far. The ground knows a");
  ("pavement is paved; only the world knows which tiles that pavement IS and which doorstep");
  ("belongs to which building, and that is what a rung is asked against.");
  let rows = app_g_map_generate();
  let blocks = app_g_bless_blocks(rows);
  app_g_bless_blocks_raise(rows, blocks);
  let coordinates = g_coordinates(rows);
  let coordinates_land = g_coordinates_land_reachable_get(coordinates);
  let player_img = g_player_img_get();
  let player = g_player_initialize(player_img, coordinates_land);
  let block_first = list_first(blocks);
  app_g_bless_player_place(player, block_first);
  let npcs = app_g_bless_people(player_img, coordinates_land, blocks, player);
  let world = app_g_bless_world(rows, coordinates, player, npcs, blocks);
  return world;
}
