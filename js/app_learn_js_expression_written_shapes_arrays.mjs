import { arguments_assert } from "./arguments_assert.mjs";
import { js_operator_minus_symbol } from "./js_operator_minus_symbol.mjs";
import { js_operator_plus_symbol } from "./js_operator_plus_symbol.mjs";
import { js_operator_asterisk_symbol } from "./js_operator_asterisk_symbol.mjs";
import { js_operator_double_asterisk_symbol } from "./js_operator_double_asterisk_symbol.mjs";
import { js_operator_bang_symbol } from "./js_operator_bang_symbol.mjs";
import { js_code_length } from "./js_code_length.mjs";
import { app_learn_js_expression_node_index } from "./app_learn_js_expression_node_index.mjs";
import { list_add } from "./list_add.mjs";
import { app_learn_js_expression_name } from "./app_learn_js_expression_name.mjs";
import { app_learn_js_expression_node } from "./app_learn_js_expression_node.mjs";
import { app_learn_js_expression_node_before } from "./app_learn_js_expression_node_before.mjs";
export function app_learn_js_expression_written_shapes_arrays() {
  arguments_assert(arguments, 0);
  ("lines that read an array's length or an item by its index, alone and inside other operators, so the sweep sees how the array lessons' two pieces print: a[a.length - 1], b[0] * 3, 2 ** b[1], !t[0]");
  ("Arrived 2026-11-09 with the brackets, which the sweep refused until a line printed them.");
  let words = ["love", "joy", "peace"];
  let numbers = [2, 4, 6];
  let truths = [true, false];
  let minus = js_operator_minus_symbol();
  let plus = js_operator_plus_symbol();
  let times = js_operator_asterisk_symbol();
  let power = js_operator_double_asterisk_symbol();
  let bang = js_operator_bang_symbol();
  let length_code = js_code_length("a");
  let shapes = [];
  let first = app_learn_js_expression_node_index("a", words, 0);
  list_add(shapes, first);
  let length = app_learn_js_expression_name(length_code, 3);
  let last_index = app_learn_js_expression_node(length, minus, 1);
  list_add(shapes, last_index);
  let last = app_learn_js_expression_node_index("a", words, last_index);
  list_add(shapes, last);
  let sum = app_learn_js_expression_node(1, plus, 1);
  let summed = app_learn_js_expression_node_index("b", numbers, sum);
  list_add(shapes, summed);
  let number_first = app_learn_js_expression_node_index("b", numbers, 0);
  let scaled = app_learn_js_expression_node(number_first, times, 3);
  list_add(shapes, scaled);
  let number_second = app_learn_js_expression_node_index("b", numbers, 1);
  let raised = app_learn_js_expression_node(2, power, number_second);
  list_add(shapes, raised);
  let raised_left = app_learn_js_expression_node(number_second, power, 2);
  list_add(shapes, raised_left);
  let truth_first = app_learn_js_expression_node_index("t", truths, 0);
  let negated = app_learn_js_expression_node_before(bang, truth_first);
  list_add(shapes, negated);
  return shapes;
}
