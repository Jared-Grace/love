import { list_find_property } from "./list_find_property.mjs";
import { equal } from "./equal.mjs";
import { not } from "./not.mjs";
import { app_g_discern_prevent } from "./app_g_discern_prevent.mjs";
import { app_g_conversation_advance } from "./app_g_conversation_advance.mjs";
import { app_g_conversation_label_for } from "./app_g_conversation_label_for.mjs";
import { list_map } from "./list_map.mjs";
import { app_g_turn_menu } from "./app_g_turn_menu.mjs";
export function app_g_conversation_render_openers(
  greeting,
  greeted,
  pending,
  npc,
  overlay,
  remaining,
  render_boundary,
  steps,
  steps_total,
  run_turn,
  pronouns,
  leave,
) {
  arguments_assert(arguments, 12);
  let intro = greeting;
  if (greeted.done) {
    intro = g_anything_else();
  }
  greeted.done = true;
  if (pending.text) {
    intro = pending.text;
    pending.text = null;
  }
  app_g_npc_says(npc, overlay, intro);
  let discern = {
    prayed: false,
  };
  ("the correct opener is READ, never drawn: it is the unplayed turn with the lowest `order`, and that order was fixed once when the conversation was generated by ",
    fn_name("g_conversation_generate"),
    ". so returning from a boundary shows the SAME correct answer, guessing always terminates, and no player can be walled in. a conversation saved before orders existed has none, and falls back to the first unplayed turn rather than leaving every choice wrong.");
  ("the fallback is where this STARTS, and the ordered answer only replaces it once there is something to order by. two separate steps refuse an absence rather than reporting one: asking a turn for an order it has not got is an error, and looking for a turn by an order that matches none of them is an error as well - the second one holding out for exactly one match. so a conversation saved before orders existed used to die twice over on the way to a fallback that could never be reached, and the player was left looking at a greeting and a 'one moment, please' that never went away.");
  let ordered = list_filter_property_exists(remaining, "order");
  let ordered_count = list_size(ordered);
  let correct_turn = list_first(remaining);
  if (positive_is(ordered_count)) {
    let orders = list_map_property(ordered, "order");
    let order_min = list_min(orders);
    correct_turn = list_find_property(ordered, "order", order_min);
  }
  function choice_of(turn) {
    let is_correct = equal(turn, correct_turn);
    async function on_click() {
      if (not(is_correct)) {
        if (app_g_discern_prevent(discern)) {
          return;
        }
        render_boundary(turn);
        return;
      }
      await app_g_conversation_advance(steps, steps_total);
      run_turn(turn);
    }
    let choice = {
      label: app_g_conversation_label_for(turn, pronouns),
      on_click,
      correct: is_correct,
    };
    return choice;
  }
  let choices = list_map(remaining, choice_of);
  app_g_turn_menu(
    overlay,
    "What would you like to say?",
    choices,
    discern,
    leave,
  );
}
