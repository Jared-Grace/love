import { arguments_assert } from "./arguments_assert.mjs";
import { folder_home_repo } from "./folder_home_repo.mjs";
import { path_join } from "./path_join.mjs";
import { fn_name } from "./fn_name.mjs";
import { text_combine_multiple } from "./text_combine_multiple.mjs";
export function git_hook_commit_msg_text() {
  "The text of the hook git runs over a commit message before making the commit - the one original every installed copy is written from.";
  "The dispatcher is named from the root, because a hook runs with the repository being committed as its folder and that is usually not this one. The folder is asked of the machine rather than worked out from where this file sits, so that the gate comparing this against the installed copies gets the same answer from inside the frozen tree it runs in.";
  "THE SHELL DECIDES ON A READING RATHER THAN ON AN EXIT CODE. A checker that cannot run at all - a file half written by a peer mid sweep, a dependency momentarily missing - exits nonzero exactly like a refusal, and a hook that read it that way would stop every peer committing at the worst possible moment. So only the word that says refuse blocks anything, and everything else lets the commit through.";
  arguments_assert(arguments, 0);
  let folder = folder_home_repo("love");
  let dispatcher = path_join([folder, "scripts", "ai.mjs"]);
  let f_name = fn_name("git_hook_commit_msg_text");
  let f_name2 = fn_name("git_hook_commit_msg_write");
  let f_name3 = fn_name("git_hook_commit_msg_gate_run");
  let f_name4 = fn_name("git_hook_commit_msg_verdict");
  let text = text_combine_multiple([
    "#!/bin/sh\n",
    "# GENERATED by ",
    f_name,
    " - do not edit by hand.\n",
    "# Install every copy with `node scripts/ai.mjs ",
    f_name2,
    "`;\n",
    "# drift from this original fails `q` via ",
    f_name3,
    ".\n",
    "#\n",
    "# Refuses a commit message whose first word is a shorthand key. A key can be\n",
    "# repointed with one command, and every commit already carrying it then reads as\n",
    "# a record of a change made by whatever it points at today.\n",
    "#\n",
    "# IT FAILS OPEN ON PURPOSE: only an explicit refusal blocks, so a checker that\n",
    "# cannot run lets the commit through instead of stopping every peer at once.\n",
    "v=$(node ",
    dispatcher,
    " ",
    f_name4,
    ' "$1" 2>&1)\n',
    "if printf '%s' \"$v\" | grep -q '\"refuse\": *true'; then\n",
    "  printf '%s\\n' \"$v\" >&2\n",
    "  exit 1\n",
    "fi\n",
    "exit 0\n",
  ]);
  return text;
}
