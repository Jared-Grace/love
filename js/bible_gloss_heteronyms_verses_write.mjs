import { text_combine_multiple } from "./text_combine_multiple.mjs";
import { arguments_assert } from "./arguments_assert.mjs";
import { local_function_folder } from "./local_function_folder.mjs";
import { app_learn_eng_gloss_urdu_generate } from "./app_learn_eng_gloss_urdu_generate.mjs";
import { py_script_speech_json_report } from "./py_script_speech_json_report.mjs";
import { fn_name } from "./fn_name.mjs";
import { property_get } from "./property_get.mjs";
import { file_overwrite_json } from "./file_overwrite_json.mjs";
import { function_constant_json_write } from "./function_constant_json_write.mjs";
export async function bible_gloss_heteronyms_verses_write() {
  "Writes, for every word a button says two ways, the verses that say it the other way and that other saying - so a word tapped in a verse about a person's life plays 'lyvz' and not the verb. Returns the verses kept for each second saying.";
  ("★ THE READER CHOOSES PER VERSE, NOBODY PICKS. Each English verse is said in its own sentence and the saying used is kept wherever it differs from the button's usual one, which is the bible's most common saying, written by ",
    fn_name("bible_audio_heteronyms_said_write"),
    ". Measured 2026-11-28: 36 words, 377 verses.");
  ("The English verses are read from the Urdu store's chapters because every store carries the same English text, verse by verse; a verse number names the same verse in all of them, so one table serves every language a reader picks.");
  ("Two files come out: the second sayings, which the speech engine records under names like lives-2, and a table the page imports to know which verses ask for them. Re-running rewrites both whole. Record the new names afterwards with ",
    fn_name("english_words_sound_remake"),
    ".");
  arguments_assert(arguments, 0);
  let folder = local_function_folder(app_learn_eng_gloss_urdu_generate);
  let args = {
    folder,
  };
  let reported = await py_script_speech_json_report(
    fn_name("bible_gloss_heteronyms_verses"),
    args,
  );
  let alternates = property_get(reported, "alternates");
  let places = property_get(reported, "places");
  await file_overwrite_json(
    "./data/given/speech_pronunciations_alone_bible_other.json",
    alternates,
  );
  let combined = text_combine_multiple([
    "★ GENERATED by ",
    fn_name("bible_gloss_heteronyms_verses_write"),
    " - never edit by hand; run it again after the English bible or the speech engine changes.",
  ]);
  let prose = [
    "Every verse whose word is said the other way from that word's button, keyed by the name the other saying is recorded under: lives-2 is lives said as in a person's life. Each place is a chapter code and a verse number.",
    combined,
  ];
  await function_constant_json_write(
    fn_name("english_word_sound_verses"),
    prose,
    places,
  );
  return places;
}
