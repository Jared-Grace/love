import { commands_only_level_off } from "./commands_only_level_off.mjs";
export function commands_only_levels() {
  "every setting the commands-only switch can be turned to, least limiting first";
  "a dial rather than an on and an off, because the two halves of the goal are ready at different times. The repo can already make any change to its own javascript through a named transform, so that half can be held to it today. The half that would replace the operating system's own commands with one portable set of names cannot be held to anything yet - there is no atom at all for searching text across files - so a single on would turn on a rule nothing can obey.";
  "the way back is a setting rather than the absence of one, so reverting is the same kind of act as setting it and leaves the same record.";
  let off = commands_only_level_off();
  let levels = [off, "js", "files"];
  return levels;
}
