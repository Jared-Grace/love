import { lyric_video_outline_width } from "./lyric_video_outline_width.mjs";
import { lyric_video_screen_room } from "./lyric_video_screen_room.mjs";
import { lyric_video_screen_characters_max } from "./lyric_video_screen_characters_max.mjs";
import { lyric_video_lead_seconds } from "./lyric_video_lead_seconds.mjs";
import { subtitles_time_text } from "./subtitles_time_text.mjs";
import { number_is } from "./number_is.mjs";
import { subtract } from "./subtract.mjs";
import { lyric_video_line_size_text } from "./lyric_video_line_size_text.mjs";
export function lyric_video_subtitles_text(document) {
  "$plain document";
  "The whole subtitle file of a lyric video, written out of one authored document: the passage and the translation that stand at the foot of every frame, how long the song runs, how big the frame is, how big the three lettering sizes are, and the lines with the moment each is sung.";
  "THE TIMES ARE AUTHORED, NOT WORKED OUT HERE. Where a sung line begins is heard, not derived - a singer holds a word, an instrument plays alone for eight bars, a verse is repeated and the printed text is not. Nothing about the words on the page says any of that, so a rule that placed them would be guessing at the one thing the video exists to get right. This packs what somebody heard; it never decides it.";
  "★ EVERY CARD IS PUT UP THE SAME MOMENT EARLIER THAN THE LINE IT HOLDS, WHICH IS NOT AN EXCEPTION TO THE PARAGRAPH ABOVE. That paragraph refuses to work out where a line belongs; this moves every card by one number that has nothing to do with which line it is, in the way the fade beside it is one number for every card. A reader needs a moment to take a line in, so a card arriving exactly on the first note is already late for them, and the times stay in the document exactly as they were heard. How far ahead, and why both ends of a card move rather than only its beginning, live with the number itself.";
  "A LINE THE DOCUMENT HAS NO TIME FOR IS LEFT OUT OF THE VIDEO RATHER THAN PLACED SOMEWHERE. It follows from the line above: where a line belongs is heard and nothing here can hear it, so there is no moment to put it at that would not be invented. Leaving it out loses a line of the psalm, which is a real loss and a visible one - the person who timed the passage watches the video and sees at once that they stopped one line early. The alternative loses the whole video quietly, because a line given a time it never had is a card standing over the singing at the wrong moment, and the worst of those times is zero, which puts it over every other line from the first frame to the last.";
  "EVERY LETTERING SIZE IS ASKED FOR, AND THE SMALLER ONES USED TO BE WORKED OUT AS A SHARE OF THE LARGER. Tying them together says they are one decision, and they are not: the words are sized to be read across a room from a phone lying on a table, the passage to be read at a glance by somebody arriving in the middle, and the translation to be findable by somebody who wants it without ever competing with the psalm. Making the words bigger through a fixed share drags all of that up with them into exactly that competition, and the only way out was to change a number that no document could see.";
  "EVERY LINE OF LETTERING CARRIES A BLACK BORDER, AND THAT ONE IS WORKED OUT RATHER THAN ASKED FOR. It is the exception the paragraph above does not cover, because a border is not a decision about who is reading; it is a fact about the letters it runs around, and it is asked for by its own lettering size alone. The reasoning lives with the border rather than here.";
  "THE BORDER GOES IN AHEAD OF ANYTHING FOR IT TO BE SEEN AGAINST. A frame here is black today, and a black rim on a black frame is invisible - so this changes nothing anybody can watch. It stops mattering the first time a picture stands behind the words, and at that moment the words either survive or they do not, with no chance to try the border on its own. A change that can only be judged after another change has landed is a change to make first.";
  "THE PASSAGE AND THE TRANSLATION ARE TWO LINES RATHER THAN ONE, AND THE SIZES ARE WHY. They used to be one grey line with a dot between them, which forced both to be the same size - so making the passage large enough to read at a glance would have made the translation shout, and keeping the translation quiet kept the passage unreadable. Stacked, each is sized for what it is for: the passage above and large, the translation under it and small.";
  "WHERE THE UPPER LINE SITS IS WORKED OUT AND NOT AUTHORED. It has to clear the line beneath it, so its distance from the foot follows from that line's lettering size; a document that stated both would be stating one fact twice, and the two would part company the first time somebody changed a size.";
  "The words come from the translation unchanged, down to the couplet that begins in the lower case because it is the second half of a line. Repairing that capital would be correcting the poem to look like prose.";
  "Every line is one whole card rather than a word lit up at a time. A word-by-word sweep asks the reader to watch the screen; a card asks them to read it and then listen, which is what a psalm is for.";
  "Both lines at the foot stand through the whole song in grey, quiet enough to be ignored and always there. Together they are the attribution the translation asks for, and they also answer the question a person arriving in the middle of a video actually has.";
  "★ THE WORDS SIT AT THE MIDDLE OF THE ROOM ABOVE THE PASSAGE LINE, NOT AT THE MIDDLE OF THE FRAME, AND THE POINT IS WORKED OUT RATHER THAN AUTHORED. They sit high rather than at the foot because a phone is held with the lower part of the screen under a thumb; they sit at the middle of what is free rather than of the whole because the foot is not free - the passage and the translation stand there through every frame there is. A card centred on the frame can only grow downwards as far as that passage line, and honesty about that limit forces it to leave the same room unused above, so a third of the frame does nothing and a long card is made smaller than it had to be. The point is worked out from the sizes at the foot for the same reason the upper of those two lines is: a document that stated it as well would be stating one fact twice, and the two would part company the first time somebody changed a size.";
  "★ THE MIDDLE IS STATED OUTRIGHT RATHER THAN ASKED FOR BY NAMING AN ALIGNMENT, because a subtitle that is merely aligned is moved out of the way of any other subtitle standing at the same moment - and the passage and the translation stand at every moment there is. A short card never grows far enough to touch them and so never moved; a card of ten lines does, and it was shifted downwards until it began below the passage and ran off the bottom of the frame, with nothing at all in the two thirds above it. Naming the point instead is what a placed card means, and a placed card is never moved. Where the point is put used to be exactly where an alignment would have put it, and is not any more: it has been raised into the room above the passage line, for the reason the line above gives.";
  "★ A CARD TOO LONG FOR THE FRAME IS SET SMALLER RATHER THAN CUT IN TWO, AND THE ALTERNATIVE IS WHY. Cutting it needs a moment to cut at, and for spoken words there is none to be had: the voice model hands back sound with no times inside it, so the join could only be placed by reasoning from how long the words are and hoping the reader crossed it there. The size, by contrast, is read off the words themselves and nothing is supposed about the reading. A song never meets this, because its lines are short and were placed by ear; a chapter meets it wherever one sentence runs a long way, and the size is written into the card itself so only that card is affected and the rest of the chapter stands as it always did.";
  "The borders grow with the frame along with everything else, because the head already says so once for the whole file.";
  "★ THE MARGINS, THE POINT THE CARD IS CENTRED ON AND HOW MUCH ROOM A CARD HAS ARE ALL ASKED FOR IN ONE PLACE RATHER THAN WORKED OUT HERE. Whoever cuts a chapter into cards has to know the same three things before this ever runs, and while this held its own copy of them the two answers drifted: cards were cut to a width that was never measured and drawn at one that was, and the first anybody knew of it was a card clipped off the top of the frame and standing over the passage line at the foot.";
  let width = document.width;
  let height = document.height;
  let font_size = document.font_size;
  let passage_size = document.passage_font_size;
  let credit_size = document.credit_font_size;
  let lyric_outline = lyric_video_outline_width(font_size);
  let passage_outline = lyric_video_outline_width(passage_size);
  let credit_outline = lyric_video_outline_width(credit_size);
  let room = lyric_video_screen_room(document);
  let credit_margin = room.credit_margin;
  let passage_margin = room.passage_margin;
  let side_margin = room.side_margin;
  let sides = side_margin + "," + side_margin;
  let styles_format =
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding";
  let lyric_style =
    "Style: Lyric,Noto Sans," +
    font_size +
    ",&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1," +
    lyric_outline +
    ",0,5," +
    sides +
    ",0,1";
  let passage_style =
    "Style: Passage,Noto Sans," +
    passage_size +
    ",&H00B4B4B4,&H00B4B4B4,&H00000000,&H00000000,0,0,0,0,100,100,2,0,1," +
    passage_outline +
    ",0,2," +
    sides +
    "," +
    passage_margin +
    ",1";
  let credit_style =
    "Style: Credit,Noto Sans," +
    credit_size +
    ",&H00828282,&H00828282,&H00000000,&H00000000,0,0,0,0,100,100,2,0,1," +
    credit_outline +
    ",0,2," +
    sides +
    "," +
    credit_margin +
    ",1";
  let middle_x = room.middle_x;
  let middle_y = room.middle_y;
  let lyric_place = "\\pos(" + middle_x + "," + middle_y + ")\\fad(260,320)";
  let characters_max = lyric_video_screen_characters_max();
  let lead = lyric_video_lead_seconds();
  let song_end = subtitles_time_text(document.duration);
  let passage_event =
    "Dialogue: 0,0:00:00.00," +
    song_end +
    ",Passage,,0,0,0,,{\\fad(900,900)}" +
    document.passage;
  let credit_event =
    "Dialogue: 0,0:00:00.00," +
    song_end +
    ",Credit,,0,0,0,,{\\fad(900,900)}" +
    document.credit;
  let head = [
    "[Script Info]",
    "ScriptType: v4.00+",
    "PlayResX: " + width,
    "PlayResY: " + height,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    styles_format,
    lyric_style,
    passage_style,
    credit_style,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    passage_event,
    credit_event,
  ];
  function line_timed_is(line) {
    let started = number_is(line.start);
    let ended = number_is(line.end);
    let r = started && ended;
    return r;
  }
  function line_event(line) {
    let shown_start = subtract(line.start, lead);
    let shown_end = subtract(line.end, lead);
    let event =
      "Dialogue: 0," +
      subtitles_time_text(shown_start) +
      "," +
      subtitles_time_text(shown_end) +
      ",Lyric,,0,0,0,,{" +
      lyric_place +
      lyric_video_line_size_text(line, font_size, characters_max) +
      "}" +
      line.text;
    return event;
  }
  let lines_heard = document.lines.filter(line_timed_is);
  let events = lines_heard.map(line_event);
  let written = head.concat(events).join("\n") + "\n";
  return written;
}
