import { arguments_assert } from "./arguments_assert.mjs";
import { html_style_set } from "./html_style_set.mjs";
export function html_style_position_relative(component) {
  arguments_assert(arguments, 1);
  ("let a thing be shown away from where the page put it, while it keeps every bit of the room the page gave it - so nothing around it notices it has moved");
  html_style_set(component, "position", "relative");
}
